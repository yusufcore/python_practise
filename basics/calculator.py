a = int(input("Enter the first number: "))
b = int(input("Enter the second number: "))

add = a + b
subtract = a - b
multiply = a * b
divide = a/b
remainder = a%b
power = a**b

print(f"The sume of {a} and {b} is: {add}")
print(f"The difference of {a} and {b} is: {subtract}")
print(f"The product of {a} and {b} is: {multiply}")
print(f"The quotient of {a} and {b} is: {divide}")
print(f"The remainder when {a} is divided by {b} is: {remainder}")
print(f"{a} raised to the power of {b} is: {power}")